#!/usr/bin/env python3
"""Battery-life budget.  Writes docs/06-power-budget.md.

EVERY load figure here is a design estimate, not a measurement.  They are
there so the battery can be sized and so Phase 7 has numbers to check
against.  Replace them with bench measurements and re-run.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# watts at the 5 V rail (or 3V3 where noted), by operating mode
LOADS = {
    #                               active  idle   note
    "CM5 SoM (CPU + Wi-Fi on)":      (4.00, 2.40, "estimate; CPU capped to 2 cores / 1.5 GHz on battery"),
    "Display + touch":               (1.00, 0.40, "estimate; ~60 % vs ~15 % backlight"),
    "Port A MAC + PHY":              (0.90, 0.10, "estimate; gigabit link vs PHY powered down"),
    "Port B (SoM PHY)":              (0.20, 0.05, "estimate; usually unlinked"),
    "Coprocessor, AFE, relays":      (0.35, 0.05, "estimate; relays only energised during a wiremap scan"),
    "PoE isolated supply":           (0.25, 0.00, "estimate; enabled only while measuring"),
    "LEDs, buzzer, misc":            (0.10, 0.05, "estimate"),
}
BOOST_EFF = 0.90          # TPS61088 at ~1 A out, 3.6 V in (datasheet-curve estimate)
USABLE = 0.90             # usable fraction of rated capacity (cut-off, ageing margin)
CELL_WH = 3.6 * 5.0       # one 21700 5000 mAh cell
PROFILES = {              # fraction of time in the active state
    "Typical field day (35 % testing, 65 % idle/dimmed)": 0.35,
    "Heavy (70 % testing)": 0.70,
    "Continuous testing": 1.00,
}
STANDBY_W = 0.004         # SoM off, coprocessor + fuel gauge alive (estimate)
TARGET_H = 8.0


def main() -> None:
    active = sum(a for a, _, _ in LOADS.values()) / BOOST_EFF
    idle = sum(i for _, i, _ in LOADS.values()) / BOOST_EFF
    out = ["# 06 - Power budget", "",
           "Generated by `tools/power_budget.py`. **All load figures are estimates, not "
           "measurements.** No NetScope hardware exists yet; Phase 7 replaces them with bench "
           "data and this file is regenerated.", "",
           "## Loads", "", "| Load | Active W | Idle W | Basis |", "|---|---:|---:|---|"]
    for name, (a, i, note) in LOADS.items():
        out.append(f"| {name} | {a:.2f} | {i:.2f} | {note} |")
    out += [f"| **Total at the rail** | **{active * BOOST_EFF:.2f}** | **{idle * BOOST_EFF:.2f}** | |",
            f"| **From the battery** (boost {BOOST_EFF:.0%}) | **{active:.2f}** | **{idle:.2f}** | |", "",
            "## Runtime", "",
            f"Usable capacity is taken as {USABLE:.0%} of rated. Target: {TARGET_H:g} h typical.", "",
            "| Profile | Avg W | 1S2P (36 Wh) | 1S3P (54 Wh) |", "|---|---:|---:|---:|"]
    results = {}
    for name, frac in PROFILES.items():
        avg = frac * active + (1 - frac) * idle
        h2, h3 = 2 * CELL_WH * USABLE / avg, 3 * CELL_WH * USABLE / avg
        results[name] = (h2, h3)
        out.append(f"| {name} | {avg:.2f} | {h2:.1f} h | {h3:.1f} h |")
    typ2, typ3 = next(iter(results.values()))
    standby_days = 3 * CELL_WH * USABLE / STANDBY_W / 24
    out += ["", "## Reading", "",
            f"- A two-cell pack gives about {typ2:.1f} h on the typical profile: "
            f"{'meets' if typ2 >= TARGET_H else 'short of'} the {TARGET_H:g} h target.",
            f"- A three-cell pack gives about {typ3:.1f} h: "
            f"{'meets' if typ3 >= TARGET_H else 'short of'} the target with "
            f"{typ3 - TARGET_H:+.1f} h margin. **Rev A is designed around 1S3P.**",
            "- Continuous testing does not reach 8 h on either pack. The 8 h claim is for the "
            "typical profile only and must not be advertised more broadly until measured.",
            f"- Standby (SoM off, coprocessor alive, ~{STANDBY_W * 1000:.0f} mW estimate): "
            f"about {standby_days:.0f} days. Cold boot from standby is a full Linux boot "
            "(target under 20 s, unmeasured); the SoM has no suspend-to-RAM we can rely on.",
            "- Peak: the SoM is specified for up to 5 A at 5 V. At 3.3 V battery that is about "
            f"{25 / 3.3 / BOOST_EFF:.1f} A from the pack, at the edge of the boost converter. "
            "The CPU cap on battery is what keeps peaks inside the budget; see risk R-05.",
            "- PoE load tests dissipate the PoE's power, not the battery's.", "",
            "## What Phase 7 must measure", "",
            "1. SoM current at idle, during a scan, and during an iperf3 run, with the CPU cap applied.",
            "2. Backlight current against brightness.",
            "3. Boost efficiency at 3.3 V, 3.7 V and 4.1 V input.",
            "4. Full discharge runtime on the typical profile script (`docs/09`, test PWR-04).", ""]
    (ROOT / "docs/06-power-budget.md").write_text("\n".join(out))
    print(f"active {active:.2f} W, idle {idle:.2f} W from battery; typical {typ2:.1f} h (2P) / {typ3:.1f} h (3P)")


if __name__ == "__main__":
    main()
