#!/usr/bin/env python3
"""Roll hardware/bom/bom.csv up into docs/14-bom-and-cost.md.

Prices in the BOM are planning estimates entered by hand, not distributor
quotes.  The links this script writes are distributor *searches* for each
part number so that every line can be quoted before an order.
"""
import csv
from pathlib import Path
from urllib.parse import quote_plus

ROOT = Path(__file__).resolve().parents[1]
QTYS = [("1", "cost_1"), ("10", "cost_10"), ("100", "cost_100"), ("1,000", "cost_1000")]
SERVICE = {"pcb", "pcb_lower", "assembly", "enclosure", "keypad", "spreader", "hardware", "terminator", "test"}
OPTIONS = {"sd_reader", "sd_socket"}


def links(mpn: str) -> str:
    q = quote_plus(mpn)
    return (f"[DigiKey](https://www.digikey.com/en/products/result?keywords={q}) "
            f"[Mouser](https://www.mouser.com/c/?q={q})")


def main() -> None:
    with (ROOT / "hardware/bom/bom.csv").open(newline="") as f:
        rows = list(csv.DictReader(f))
    tot = {c: {"parts": 0.0, "service": 0.0, "options": 0.0} for _, c in QTYS}
    for r in rows:
        group = "options" if r["key"] in OPTIONS else "service" if r["key"] in SERVICE else "parts"
        for _, c in QTYS:
            tot[c][group] += float(r[c]) * int(r["qty"])
    status = {s: sum(1 for r in rows if r["mpn_status"] == s and r["key"] not in SERVICE)
              for s in ("known", "candidate", "tbd")}

    out = ["# 14 - Bill of materials and cost estimate", "",
           "Generated by `tools/cost_rollup.py` from `hardware/bom/bom.csv`.", "",
           "**These are planning estimates, not quotes.** Unit costs were entered from general "
           "knowledge of 2026 pricing and have not been checked line by line against live "
           "distributor stock. Two were checked against published list prices on 2026-11-10: "
           "the Compute Module 5 family (the maker's July 2026 product brief) and the 5 inch "
           "Touch Display 2 ($40 list). Quote every line before ordering.", "",
           "## Cost per unit", "",
           "| | " + " | ".join(q for q, _ in QTYS) + " |", "|---|" + "---:|" * len(QTYS)]
    for label, key in (("Electronic parts", "parts"),
                       ("PCB, assembly, mechanics, terminator, test", "service")):
        out.append(f"| {label} | " + " | ".join(f"${tot[c][key]:,.0f}" for _, c in QTYS) + " |")
    out.append("| **Total per unit** | " + " | ".join(
        f"**${tot[c]['parts'] + tot[c]['service']:,.0f}**" for _, c in QTYS) + " |")
    out.append("| Optional (microSD reader, M.2 socket) | " + " | ".join(
        f"+${tot[c]['options']:,.1f}" for _, c in QTYS) + " |")
    out += ["",
            "Not included: injection-mould tooling (budget $25k-$45k for two shells, bumper and "
            "keypad), regulatory testing (FCC Part 15B and battery UN38.3 at minimum; budget "
            "$8k-$20k, see `docs/10`), engineering time, scrap, freight, tariffs and margin.", "",
            f"Prototype run of 5 boards: about ${5 * (tot['cost_1']['parts'] + tot['cost_1']['service']):,.0f} "
            "in parts and services, plus a second spin (assume one).", "",
            "## Part-number confidence", "",
            f"- **known** ({status['known']}): an orderable part number I am confident exists. "
            "Suffix, package and stock still need checking.",
            f"- **candidate** ({status['candidate']}): believed suitable; confirm against the datasheet.",
            f"- **tbd** ({status['tbd']}): only the requirement is fixed. Selecting these is Phase 2/3 work.", "",
            "## Lines", "",
            "| Refs | Qty | Description | Manufacturer / MPN | Status | $ @1 | $ @100 | $ @1k | Find | Alternates | Supply risk |",
            "|---|---:|---|---|---|---:|---:|---:|---|---|---|"]
    for r in rows:
        mpn = r["mpn"] if r["mpn"] not in ("TBD", "-") else ""
        find = links(mpn) if mpn and r["mpn_status"] != "tbd" else ""
        out.append(f"| {r['refs']} | {r['qty']} | {r['description']} | {r['manufacturer']} {mpn} | "
                   f"{r['mpn_status']} | {float(r['cost_1']):.2f} | {float(r['cost_100']):.2f} | "
                   f"{float(r['cost_1000']):.2f} | {find} | {r['alternates']} | {r['lifecycle_risk']} |")
    out.append("")
    (ROOT / "docs/14-bom-and-cost.md").write_text("\n".join(out))
    print("per unit:", ", ".join(f"{q}: ${tot[c]['parts'] + tot[c]['service']:,.0f}" for q, c in QTYS),
          "| mpn status:", status)


if __name__ == "__main__":
    main()
