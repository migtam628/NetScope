#!/usr/bin/env python3
"""Generate the RT-1 remote terminator schematic (KiCad 9) from the firmware's definition.

    python tools/gen_rt1.py        # writes hardware/remote-terminator/kicad/rt-1/rt-1.kicad_sch

Unlike the main-board project this is real capture: KiCad library symbols with
real pin numbers, and a footprint on every part.  The element values and pin
pairs come from firmware/netscope/cable/terminator.py, the single source of
truth, so the board and the analyser cannot drift apart.

Then: tools/layout_rt1.py (board), tools/check_rt1.py (ERC, DRC, netlist).
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "firmware"))
sys.path.insert(0, str(ROOT / "tools"))

from kicad_lib import Sheet  # noqa: E402
from netscope.cable.terminator import ID_PAIR, ID_RESISTORS, PAIR_RESISTORS, PAIRS  # noqa: E402

OUT = ROOT / "hardware/remote-terminator/kicad/rt-1"
JACK_FP = "Connector_RJ:RJ45_Amphenol_54602-x08_Horizontal"
DIODE_FP = "Diode_SMD:D_SOD-123"
RES_FP = "Resistor_SMD:R_2512_6332Metric"


def ohms(v: float) -> str:
    """1000 -> 1k, 2200 -> 2k2, 150000 -> 150k."""
    k = v / 1000
    if k == int(k):
        return f"{int(k)}k"
    whole, frac = str(k).split(".")
    return f"{whole}k{frac}"


def elements():
    """[(index, anode pin, cathode pin, value text)] in firmware order."""
    out = []
    for i, (a, c) in enumerate(PAIRS, 1):
        if (a, c) == ID_PAIR:
            lo, hi = min(ID_RESISTORS.values()), max(ID_RESISTORS.values())
            out.append((i, a, c, f"{ohms(lo)}-{ohms(hi)} by ID"))
        else:
            out.append((i, a, c, ohms(PAIR_RESISTORS[(a, c)])))
    return out


def build() -> str:
    s = Sheet("rt-1", "netscope-x1/rt-1", "NetScope RT-1 remote terminator")
    s.comments = ["UNTESTED rev A. Values from firmware/netscope/cable/terminator.py.",
                  "Generated by tools/gen_rt1.py"]
    jack = s.symbol("Connector:RJ45", "J1", "RJ45 jack, unshielded", (50.8, 88.9), footprint=JACK_FP,
                    fields={"Manufacturer": "Amphenol", "MPN": "54602-908LF"},
                    ref_at=(45.72, 71.12), value_at=(45.72, 104.14))
    for n in range(1, 9):
        x, y = jack[str(n)]
        s.wire((x, y), (x + 5.08, y))
        s.label(f"P{n}", (x + 5.08, y), "right")

    for i, a, c, value in elements():
        y = 50.8 + i * 15.24
        d = s.symbol("Diode:1N4148W", f"D{i}", "1N4148W", (127.0, y), 180, DIODE_FP,
                     fields={"MPN": "1N4148W (any maker, SOD-123)"},
                     ref_at=(127.0, y - 3.81), value_at=(127.0, y + 3.81))
        r = s.symbol("Device:R", f"R{i}", value, (146.05, y), 90, RES_FP,
                     fields={"Tolerance": "1%", "Rating": "1 W or more (see README: fault dissipation)"},
                     ref_at=(146.05, y - 3.81), value_at=(146.05, y + 3.81))
        s.wire((115.57, y), d["2"])                 # anode side
        s.label(f"P{a}", (115.57, y), "left")
        s.wire(d["1"], r["1"])                      # cathode to resistor
        s.wire(r["2"], (157.48, y))
        s.label(f"P{c}", (157.48, y), "right")
        s.text(f"pair {a}-{c}: forward (pin {a} positive) reads {value.split(' ')[0]}, reverse reads open",
               (165.1, y + 0.6), 1.27)

    s.text("NetScope RT-1 remote terminator, rev A. UNTESTED: not built, not measured.", (25.4, 25.4), 2.0)
    s.text("One series diode + resistor per pair. Diode anode on the first pin of the pair.", (25.4, 31.75))
    id_row = ID_PAIR and next(i for i, a, c, _ in elements() if (a, c) == ID_PAIR)
    table = "   ".join(f"ID {k} = {ohms(v)}" for k, v in sorted(ID_RESISTORS.items()))
    s.text(f"R{id_row} sets the terminator ID:   {table}", (25.4, 139.7))
    s.text("R1-R4 are 2512 so power-rated parts can be fitted. A passive 57 V injector on a miswired run puts",
           (25.4, 149.86), 1.27)
    s.text("3.2 W in a 1k part, 1.5 W in 2k2, 0.7 W in 4k7 and 0.33 W in 10k. Surviving that is NOT yet designed or tested.",
           (25.4, 152.4), 1.27)
    s.text("No connection to the cable shield: J1 is unshielded and the wiremap does not test the shield.",
           (25.4, 157.48), 1.27)
    return s.render("MT Tech Services LLC")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "rt-1.kicad_sch").write_text(build())
    pro = OUT / "rt-1.kicad_pro"
    if not pro.exists():
        pro.write_text('{\n  "meta": {\n    "filename": "rt-1.kicad_pro",\n    "version": 3\n  }\n}\n')
    print(f"wrote {(OUT / 'rt-1.kicad_sch').relative_to(ROOT)}: J1 + {len(PAIRS)} diode/resistor elements")


if __name__ == "__main__":
    main()
