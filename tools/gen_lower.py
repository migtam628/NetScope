#!/usr/bin/env python3
"""Generate the lower (keypad and USB-C) board schematic, KiCad 9.

    python3 tools/gen_lower.py     # writes hardware/kicad/netscope-x1-lower/netscope-x1-lower.kicad_sch

Real capture: KiCad library symbols with real pin numbers, a footprint on every
part.  Drawn label-style: every pin carries a net label, so the netlist is the
table in this file and nothing depends on drawn wires.

The nine nets that cross to the main board are the same nine the block netlist
lists; tools/check_lower.py checks that.  J50 / J51 pin assignments are defined
HERE and the main board must mirror them.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from kicad_lib import Sheet  # noqa: E402

OUT = ROOT / "hardware/kicad/netscope-x1-lower"
NAME = "netscope-x1-lower"

R0603, C0603, C0805 = "Resistor_SMD:R_0603_1608Metric", "Capacitor_SMD:C_0603_1608Metric", "Capacitor_SMD:C_0805_2012Metric"
FP = {
    "key": "Button_Switch_THT:SW_PUSH_6mm_H9.5mm",
    "led": "LED_SMD:LED_0603_1608Metric",
    "buzzer": "Buzzer_Beeper:Buzzer_CUI_CPT-9019S-SMT",
    "usbc": "Connector_USB:USB_C_Receptacle_GCT_USB4105-xx-A_16P_TopMnt_Horizontal",
    "esd": "Package_TO_SOT_SMD:SOT-666",
    "ffc30": "Connector_FFC-FPC:Hirose_FH12-30S-0.5SH_1x30-1MP_P0.50mm_Horizontal",
    "ffc20": "Connector_FFC-FPC:Hirose_FH12-20S-0.5SH_1x20-1MP_P0.50mm_Horizontal",
    "hole": "MountingHole:MountingHole_2.7mm_M2.5",
}

# Keys in firmware order: (reference, net, legend)
KEYS = [("SW1", "KEY_UP", "Up"), ("SW2", "KEY_DOWN", "Down"), ("SW3", "KEY_LEFT", "Left"),
        ("SW4", "KEY_RIGHT", "Right"), ("SW5", "KEY_OK", "OK"), ("SW6", "KEY_BACK", "Back"),
        ("SW7", "KEY_HOME", "Home"), ("SW8", "KEY_FN", "Fn"), ("SW9", "KEY_PWR", "Power")]
LEDS = ["LED1", "LED2", "LED3", "LED4"]

# J50, 30-way signal cable.  Pin 1 is the end nearest the board centre.  The order follows where each
# net goes on the board (LEDs along the top, then the right-hand side, USB and CC down the middle,
# the left key cluster last) so the fan-out from the connector does not cross itself.
J50 = ["GND", "LED4", "LED3", "LED2", "LED1", "GND", "KEY_PWR", "KEY_BACK", "BUZZ", "KEY_HOME", "KEY_FN", "GND",
       "USB_DP", "USB_DN", "GND", "CC1", "CC2", "GND", "KEY_RIGHT", "KEY_UP", "KEY_OK", "KEY_DOWN", "KEY_LEFT",
       "GND", "+3V3_AON", "+3V3_AON", "GND", None, None, "GND"]
# J51, 20-way power cable: ten contacts each way, 0.5 A per contact rating.
J51 = ["VBUS"] * 10 + ["GND"] * 10

# Which block-netlist net each cable net belongs to (for the cross-board check).
BLOCK_NET = {"USB_DP": "USBC_D", "USB_DN": "USBC_D", "CC1": "USBC_CC", "CC2": "USBC_CC", "VBUS": "USBC_VBUS",
             "BUZZ": "BUZZ", "+3V3_AON": "+3V3_AON", "GND": "GND",
             **{k[1]: "KEYS" for k in KEYS}, **{led: "STATUS_LEDS" for led in LEDS}}


def build() -> Sheet:
    s = Sheet(NAME, "netscope-x1/lower", "NetScope X1 keypad and USB-C board", "A3")
    s.comments = ["UNTESTED rev A. Generated by tools/gen_lower.py", "J50 / J51 pin assignments are defined here"]
    s.text("NetScope X1 lower board (keys, status LEDs, buzzer, USB-C), rev A. UNTESTED: not built, not measured.",
           (20.32, 20.32), 2.2)

    # ---- USB-C -------------------------------------------------------------
    s.text("USB-C: charging input and USB 2.0. D30 pin 5 is left open on purpose: the data lines are still",
           (20.32, 43.18))
    s.text("clamped by the part's internal diode, and VBUS may then be raised above 5 V later without touching D30.",
           (20.32, 46.99))
    s.part("Connector:USB_C_Receptacle_USB2.0_16P", "J20", "USB-C 16P", (55.88, 93.98),
           {"A1": "GND", "A12": "GND", "B1": "GND", "B12": "GND", "S1": "GND",
            "A4": "VBUS", "A9": "VBUS", "B4": "VBUS", "B9": "VBUS", "A5": "CC1", "B5": "CC2",
            "A6": "USB_DP", "B6": "USB_DP", "A7": "USB_DN", "B7": "USB_DN", "A8": None, "B8": None},
           FP["usbc"], {"Manufacturer": "GCT", "MPN": "USB4105-GF-A"},
           ref_at=(48.26, 66.04), value_at=(48.26, 68.58))
    s.part("Power_Protection:USBLC6-2P6", "D30", "USBLC6-2P6", (116.84, 93.98),
           {"1": "USB_DP", "6": "USB_DP", "3": "USB_DN", "4": "USB_DN", "5": None, "2": "GND"},
           FP["esd"], {"Manufacturer": "STMicroelectronics", "MPN": "USBLC6-2P6"},
           ref_at=(124.46, 86.36), value_at=(124.46, 88.9))
    for ref, x, net in (("R1", 144.78, "CC1"), ("R2", 157.48, "CC2")):
        s.part("Device:R", ref, "5k1", (x, 93.98), {"1": net, "2": "GND"}, R0603, {"Tolerance": "1%"},
               ref_at=(x + 3.81, 92.71), value_at=(x + 3.81, 95.25))
    s.part("Device:C", "C1", "4u7 25V", (170.18, 93.98), {"1": "VBUS", "2": "GND"}, C0805, {"Dielectric": "X5R/X7R"},
           ref_at=(175.26, 92.71), value_at=(175.26, 95.25))

    # ---- status LEDs and buzzer --------------------------------------------
    s.text("Status LEDs: driven from the coprocessor through 680R. Fit LEDs with about 2 V forward drop.",
           (205.74, 43.18))
    for i, net in enumerate(LEDS, 1):
        x = 213.36 + (i - 1) * 27.94
        s.part("Device:R", f"R2{i}", "680R", (x, 63.5), {"1": net, "2": f"{net}_A"}, R0603,
               ref_at=(x + 3.81, 62.23), value_at=(x + 3.81, 64.77))
        s.part("Device:LED", net, "LED 0603", (x + 13.97, 86.36), {"2": f"{net}_A", "1": "GND"}, FP["led"],
               ref_at=(x + 13.97, 81.28), value_at=(x + 13.97, 91.44))
    s.text("Buzzer: piezo, driven directly from a timer pin. Loudness at 3.3 V is not yet measured.", (205.74, 104.14))
    s.part("Device:R", "R31", "100R", (213.36, 120.65), {"1": "BUZZ", "2": "BZ_P"}, R0603,
           ref_at=(217.17, 119.38), value_at=(217.17, 121.92))
    s.part("Device:Buzzer", "BZ1", "CPT-9019S-SMT", (243.84, 120.65), {"1": "BZ_P", "2": "GND"}, FP["buzzer"],
           {"Manufacturer": "CUI Devices", "MPN": "CPT-9019S-SMT"}, ref_at=(250.19, 119.38), value_at=(254.0, 121.92))
    s.part("Device:R", "R32", "4k7", (274.32, 120.65), {"1": "BZ_P", "2": "GND"}, R0603,
           ref_at=(278.13, 119.38), value_at=(278.13, 121.92))

    # ---- keys ----------------------------------------------------------------
    s.text("Keys: one line each, closed = low. 10k pull-up to the always-on rail and 100n on the board.",
           (20.32, 137.16))
    for i, (ref, net, legend) in enumerate(KEYS):
        cx, cy = 40.64 + (i % 3) * 63.5, 160.02 + (i // 3) * 40.64
        n = ref[2:]
        s.part("Switch:SW_Push", ref, legend, (cx, cy), {"1": net, "2": "GND"}, FP["key"],
               {"Description": "6 x 6 mm through-hole tactile switch, 9.5 mm actuator"},
               ref_at=(cx, cy - 7.62), value_at=(cx, cy - 5.08))
        s.part("Device:R", f"R1{n}", "10k", (cx + 22.86, cy), {"1": "+3V3_AON", "2": net}, R0603,
               ref_at=(cx + 26.67, cy - 1.27), value_at=(cx + 26.67, cy + 1.27))
        s.part("Device:C", f"C1{n}", "100n", (cx + 38.1, cy), {"1": net, "2": "GND"}, C0603,
               ref_at=(cx + 43.18, cy - 1.27), value_at=(cx + 43.18, cy + 1.27))

    # ---- cables to the main board -------------------------------------------
    s.text("J50: 30-way 0.5 mm FFC, signals", (320.04, 53.34))
    s.part("Connector_Generic_MountingPin:Conn_01x30_MountingPin", "J50", "FH12-30S-0.5SH", (345.44, 99.06),
           {**{str(i + 1): net for i, net in enumerate(J50)}, "MP": "GND"}, FP["ffc30"],
           {"Manufacturer": "Hirose", "MPN": "FH12-30S-0.5SH(55)"}, ref_at=(347.98, 58.42), value_at=(347.98, 60.96))
    s.text("J51: 20-way 0.5 mm FFC, power", (320.04, 165.1))
    s.part("Connector_Generic_MountingPin:Conn_01x20_MountingPin", "J51", "FH12-20S-0.5SH", (345.44, 198.12),
           {**{str(i + 1): net for i, net in enumerate(J51)}, "MP": "GND"}, FP["ffc20"],
           {"Manufacturer": "Hirose", "MPN": "FH12-20S-0.5SH(55)"}, ref_at=(347.98, 170.18), value_at=(347.98, 172.72))
    s.text("VBUS: 10 contacts, 0.5 A each. Charger input must stay at or below 3 A.", (320.04, 238.76), 1.27)

    for i in range(4):
        x = 215.9 + i * 15.24
        s.part("Mechanical:MountingHole", f"H{i + 5}", "M2.5", (x, 152.4), {}, FP["hole"],
               ref_at=(x, 147.32), value_at=(x, 157.48))
    return s


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    s = build()
    (OUT / f"{NAME}.kicad_sch").write_text(s.render("MT Tech Services LLC"))
    print(f"wrote {(OUT / (NAME + '.kicad_sch')).relative_to(ROOT)}: {len(s.netmap) + 4} parts")


if __name__ == "__main__":
    main()
